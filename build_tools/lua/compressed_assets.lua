-- Compressed input spans for the CD, which cannot read the cartridge directly.
-- Discover the assembled include graph; do not maintain a second asset list.
local assets = {}
local generated = "_definitions/Compressed Assets.asm"
local function read(path)
	local f = io.open(path, "rb")
	if not f then return nil end
	local data = f:read("*a"); f:close(); return data
end
function assets.generate()
	local seen, rows = {}, {}
	local function scan(path)
		if seen[path] or path == generated then return end
		seen[path] = true
		local source = assert(read(path), "Missing source " .. path)
		local label
		for line in source:gmatch("[^\r\n]+") do
			line = line:gsub(";.*$", "")
			label = line:match("^%s*([%w_]+):") or label
			local include = line:match('^%s*include%s+"([^"]+)"')
			if include then
				local resolved = include
				if not read(resolved) then resolved = (path:match("^(.*[/\\])") or "") .. include end
				if not read(resolved) then resolved = "_inc/" .. include end
				scan(resolved)
			end
			local file = line:match('binclude%s+"([^"]+)"')
			if file and (file:match("%.kosp$") or file:match("%.kospm$") or file:match("%.nem$") or file:match("%.eni$")) then
				assert(label, "Unlabelled compressed asset in " .. path)
				local data = assert(read(file), "Missing asset " .. file)
				local size = #data
				assert(size >= 2, "Empty/truncated compressed asset " .. file)
				assert(size <= 0x8000, "CD input buffer too small for " .. file)
				if file:match("%.nem$") then
					local tiles = (data:byte(1) % 0x80) * 0x100 + data:byte(2)
					assert(tiles > 0 and tiles * 0x20 <= 0x10000, "CD output buffer too small for " .. file)
				end
				rows[label] = {size, file}
			end
		end
	end
	scan("md-main.asm")
	local names = {}; for name in pairs(rows) do names[#names+1] = name end
	table.sort(names)
	local out = {"; Generated by build_tools/lua/compressed_assets.lua.\n",
		"; Exact cartridge spans, including interior pointers into moduled archives.\n",
		"MCD_CompressedAssets:\n\tdc.l Snd_Driver,Snd_Driver_End\n"}
	for _, name in ipairs(names) do
		out[#out+1] = string.format("\tif defined(%s)\n\tdc.l %s,%s+$%X\t; %s\n\tendif\n", name, name, name, rows[name][1], rows[name][2])
	end
	out[#out+1] = "MCD_CompressedAssets_End:\n"
	local data = table.concat(out)
	if read(generated) ~= data then
		local f = assert(io.open(generated, "wb")); f:write(data); f:close()
	end
	print(string.format("Generated %d compressed asset spans.", #names + 1))
end
return assets
