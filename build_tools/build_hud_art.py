#!/usr/bin/env python3
"""Build gameplay labels/counters from the shared Ristar CONTINUE font.

Only ten label letters are resident, arranged into shared short sprite runs.
Gameplay/counter cells are 8x8; continue text retains its 8x16 mapping cells.
Life portraits, names and their separate digit source remain independent.
"""
from pathlib import Path
from build_card_art import tiles
from import_scrap_madness import nemesis_compress

ROOT = Path(__file__).resolve().parents[1]
LABELS = 'SCORTIMENG'
LABEL_RUNS = {
    'SCORE': ((0,4,0),(7,1,32)),
    'TIME': ((4,4,0),),
    'RINGS': ((3,1,0),(5,1,8),(8,2,16),(0,1,32)),
}


def label_pieces(text, y, x, base='ArtTile_HUD', palette=1, priority=0):
    return [(y,(width-1)<<2,
             f'make_art_tile(ArtTile_HUD+{tile},{palette},{priority})-{base}',x+offset)
            for tile,width,offset in LABEL_RUNS[text]]


def lettering(text, ink=6, shadow=False, width=None, height=16):
    font = (ROOT/'art/uncompressed/Level select and Debug Mode text.bin').read_bytes()
    assert height in (8,16)
    pixels = [[0]*(width or len(text)*8) for _ in range(height)]
    for column, char in enumerate(text):
        if char == ' ':
            continue
        if char == ':':
            # The menu font has no colon (tile 10 is '$'). Match its stroke
            # weight with two square dots inside the same eight-pixel cell.
            rows = (0,0,0x18,0x18,0,0x18,0x18,0)
            glyph = bytes(((15 if row & (0x80 >> x) else 0) << 4) |
                          (15 if row & (0x40 >> x) else 0)
                          for row in rows for x in range(0,8,2))
        else:
            index = ord(char)-ord('0') if char.isdigit() else ord(char)-ord('A')+17
            glyph = font[index*32:(index+1)*32]
        assert len(glyph) == 32, char
        for y in range(8):
            for x in range(8):
                value = glyph[y*4+x//2] >> (0 if x&1 else 4) & 15
                assert value in (0,15)
                if value:
                    px, py = column*8+x, y+(4 if height==16 else 0)
                    if shadow and px+1 < len(pixels[0]) and py+1 < height:
                        pixels[py+1][px+1] = 1
                    pixels[py][px] = ink
    return tiles(pixels)


def main():
    from build_card_art import emit_table
    labels = b''.join(lettering(c,13,True,height=8) for c in LABELS)
    digits = b''.join(lettering(c,6,True,height=8) for c in '0123456789:')
    assert len(labels) == 10*32 and len(digits) == 11*32
    (ROOT/'art/nemesis/HUD.nem').write_bytes(nemesis_compress(labels))
    (ROOT/'art/uncompressed/HUD Numbers.bin').write_bytes(digits)
    # Results share the resident labels and need only private B/O/N/U tiles.
    (ROOT/'art/uncompressed/SS Results Labels.unc').write_bytes(
        lettering('BONU',13,True,height=8))
    header = '''; Generated by build_tools/build_hud_art.py. Life HUD pieces retain their original cells.
Map_Obj21_ScoreDigits = make_art_tile(ArtTile_HUD_Numbers,1,1)-ArtTile_HUD
Map_Obj21_DebugDigits = make_art_tile(ArtTile_HUD_Debug_Numbers,1,1)-ArtTile_HUD
Map_Obj21_TimeDigits = make_art_tile(ArtTile_HUD_Time,1,1)-ArtTile_HUD
Map_Obj21_RingDigits = make_art_tile(ArtTile_HUD_Rings,1,1)-ArtTile_HUD
Map_Obj21_LivesIcon = make_art_tile(ArtTile_Lives_Counter,0,1)-ArtTile_HUD
Map_Obj21_TailsIcon = make_art_tile(ArtTile_Tails_Life,0,1)-ArtTile_HUD
Map_Obj21_LivesLetters = make_art_tile(ArtTile_Lives_Counter+4,1,1)-ArtTile_HUD
'''
    frames = []
    for tails in (False,True):
        for debug,blink in ((False,False),(False,True),(True,False),(True,True)):
            score = ([( -124,12,'make_art_tile(ArtTile_HUD,1,1)-ArtTile_HUD',0),
                      (-128,13,'Map_Obj21_DebugDigits',32),
                      (-128,13,'Map_Obj21_DebugDigits+8',64)] if debug else
                     label_pieces('SCORE',-124,0,priority=1)+[
                         (-124,8,'Map_Obj21_ScoreDigits',40),
                         (-124,12,'Map_Obj21_ScoreDigits+3',64)])
            frames.append(score+label_pieces('TIME',-108,0,palette=0 if blink else 1,priority=1)+[
                (-108,12,'Map_Obj21_TimeDigits',40)]+
                label_pieces('RINGS',-92,0,priority=1)+[
                (-92,8,'Map_Obj21_RingDigits',48),
                (64,5,'Map_Obj21_TailsIcon' if tails else 'Map_Obj21_LivesIcon',0),
                (64,13,'Map_Obj21_LivesLetters',16)])
    (ROOT/'mappings/sprite/obj21.asm').write_text(
        header+emit_table('Map_Obj21_internal',frames,'normal/blinking/Debug, Sonic/Tails'))
    print('HUD: ten resident label tiles; 8x8 counters; original life HUD retained.')


if __name__ == '__main__':
    main()
