#!/usr/bin/env python3
"""Convert the five Palmtree Panic enemy art/mappings from scddisasm.

Use a read-only source checkout at f8cf3f0af7bf419d18182ba98554f09307ad3cc6.
--source names its src directory. The built ROM supplies NemDecToRAM only.
Palette 1 is adapted to Mystic Island's common player palette; transparency
and every source mapping rectangle/flip are preserved. No CD camera PLCs are
needed: all five art sets fit in a single resident interval in LV0A.
"""
from pathlib import Path
import argparse, re, struct, sys
from import_scrap_madness import nemesis_inline, palette_lookup, remap_pixels

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('Anton', 'Mosqui', 'Pata-Bata', 'Taga-Taga', 'Tamabboh')


def numeric(value):
    value = value.strip()
    return int(value[1:], 16) if value.startswith('$') else int(value)


def read_tables(source):
    tables, label = {}, None
    for line in source.splitlines():
        line = line.split(';')[0].strip()
        if ':' in line:
            label, line = line.split(':', 1)
            tables[label] = {'bytes': bytearray(), 'entries': []}
        match = re.search(r'\bdc\.([bw])\s+(.+)', line)
        if not match:
            continue
        assert label is not None
        if match[1] == 'b':
            tables[label]['bytes'].extend(numeric(x) & 255 for x in match[2].split(','))
        else:
            tables[label]['entries'].extend(x.strip().split('-')[0] for x in match[2].split(','))
    return tables


def mapping(source, root):
    tables = read_tables(source)
    entries = tables[root]['entries']
    out = bytearray(len(entries) * 2)
    seen = {}
    for i, entry in enumerate(entries):
        data = tables[entry]['bytes']
        count = data[0]
        assert len(data) >= 1 + count * 5
        frame = bytearray(struct.pack('>H', count))
        for j in range(count):
            y, size, hi, lo, x = data[1+j*5:6+j*5]
            tile = hi << 8 | lo
            assert not tile & 0x6000, 'Source rectangles use the base palette 1'
            frame.extend(struct.pack('>bBHh', y if y < 128 else y-256,
                                     size, tile, x if x < 128 else x-256))
        frame = bytes(frame)
        if frame not in seen:
            seen[frame] = len(out)
            out.extend(frame)
        struct.pack_into('>H', out, i*2, seen[frame])
    return bytes(out)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ('source', 'rom', 'listing'):
        p.add_argument('--'+name, type=Path, required=True)
    args = p.parse_args()
    # Reuse the native decompressor harness without executing its tests.
    old = sys.argv
    sys.argv = ['nemesis', '--rom', str(args.rom), '--listing', str(args.listing)]
    ns = {'__file__': str(ROOT/'build_tools/check_object_manager.py')}
    exec((ROOT/'build_tools/check_object_manager.py').read_text().split('m=Manager()')[0], ns)
    native = ns['Native']()
    sys.argv = old
    source = args.source/'Level/Palmtree Panic'
    pal = struct.unpack('>16H', (source/'Data/Palette (Present).bin').read_bytes()[:32])
    target = struct.unpack('>16H', (ROOT/'palette/SonicAndTails.bin').read_bytes()[:32])
    lut = palette_lookup(pal, target)
    cursor = 0x32B  # first tile after the LV0A GHZ terrain
    declarations = ['; Generated by import_palmtree_enemies.py; resident LV0A sprite art.']
    for name in NAMES:
        directory = source/f'Objects/{name}/Data'
        original = (directory/'Art.nem').read_bytes()
        count = int.from_bytes(original[:2], 'big') & 0x7FFF
        native.cpu.mem_write(0x300000, original)
        native.act('NemDecToRAM', limit=2000000, regs={ns['UC_M68K_REG_A0']: 0x300000,
                                                    ns['UC_M68K_REG_A4']: 0xFF0000})
        raw = remap_pixels(bytes(native.cpu.mem_read(0xFF0000, count*32)), lut)
        for folder in ('art/nemesis', 'art/uncompressed'):
            (ROOT/folder).mkdir(exist_ok=True)
        (ROOT/f'art/nemesis/PP {name}.nem').write_bytes(nemesis_inline(raw))
        (ROOT/f'art/uncompressed/PP {name}.unc').write_bytes(raw)
        label = name.replace('-', '')
        declarations.append(f'ArtTile_PP_{label}: equ ${cursor:X} ; {count} tiles')
        cursor += count
        mappings = []
        if name == 'Anton':
            mappings = [('Mappings.asm', '.Map', name)]
        elif name in ('Mosqui', 'Pata-Bata'):
            mappings = [(f'Mappings ({variant}).asm', '.Map', f'{name} {variant}')
                        for variant in ('Normal', 'Damaged')]
        else:
            prefix = 'MapSpr_'+label
            mappings = [('Mappings.asm', prefix+str(i), f'{name} {variant}')
                        for i, variant in enumerate(('Normal', 'Damaged'), 1)]
            if name == 'Tamabboh':
                mappings.append(('Mappings (Missile).asm', '.Map', 'Tamabboh Missile'))
        for filename, root, output in mappings:
            data = mapping((directory/filename).read_text(), root)
            (ROOT/f'mappings/sprite/PP {output}.bin').write_bytes(data)
            # Every rectangle stays within its original art file.
            from check_sprite_assets import frames
            for frame in frames(data):
                for _, size, tile, _ in frame:
                    assert (tile & 0x7FF) + ((size >> 2)+1)*((size & 3)+1) <= count
    assert cursor <= 0x4B4, 'Keep the generic wheel and common sprite banks free'
    declarations.append(f'ArtTile_PP_End: equ ${cursor:X}')
    (ROOT/'_inc/PalmtreeArtTiles.asm').write_text('\n'.join(declarations)+'\n')
    print(f'PP: {cursor-0x32B} tiles at $32B-${cursor:X}; palette remap {lut}; 9 enemy mapping sets + missile')


if __name__ == '__main__':
    main()
